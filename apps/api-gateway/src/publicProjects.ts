import type { Project } from './store';

export type PublicProjectSeed = {
  name: string;
  projectKey: string;
  serviceName: string;
  deploymentPlatform: Project['deploymentPlatform'];
  appUrl: string;
  description: string;
  branch: string;
  commitSha: string;
};

const project = (
  name: string,
  projectKey: string,
  appUrl: string,
  description: string,
  deploymentPlatform: Project['deploymentPlatform'] = 'Other',
  branch = 'main',
): PublicProjectSeed => ({
  name,
  projectKey,
  serviceName: `${projectKey.toLowerCase()}-site`,
  deploymentPlatform,
  appUrl,
  description,
  branch,
  commitSha: `${projectKey.toLowerCase().replace(/[^a-z0-9]/g, '').padEnd(6, '0').slice(0, 6)}${String(name.length * 97).slice(0, 4)}`,
});

